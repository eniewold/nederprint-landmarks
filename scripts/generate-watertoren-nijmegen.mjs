// NYMA-watertoren in Nijmegen (J. Buining, 1929), gemeentelijk monument sinds
// 2012. De toren is boven het fabrieksgebouw van kunstzijdefabriek Nyma
// opgetrokken: een zestienhoekig reservoir in een betonskelet van acht kolommen
// en vier ringbalken, met bovenin bakstenen panelen met het opschrift NYMA en
// daaronder grijze panelen, onder de tweede ringbalk een zigzag van schoren
// tussen de kolommen, en een laag zestienzijdig kegeldak met een lichtkoepel.
//
// De toren is geen eigen BAG-pand: hij hoort bij pand 0268100000015629, de
// hele fabriekshal van 1928 (9750 m²). Omdat de kaart en de export alleen hele
// panden kunnen verbergen, neemt de GLB de rest van dat pand over als tweede
// node (zoals de abdij bij generate-lange-jan.mjs): de dakvlakken van de 3D BAG
// (LoD2.2, CC BY 4.0, fabriekBag3d() onderaan het script) als prisma's onder
// hun eigen dakvlak, met de torendelen op de hoogte van het fabrieksdak.
//
// Oorsprong op het hart van het reservoir in het AHN (cirkelfit op de rand
// tussen 12 en 22 m) op maaiveld (NAP +14,29 m, het plein ten noordoosten),
// assen in RD-richting. De stand van de kolommen is niet bekend (op de RD-assen
// en de diagonalen). Hoogtes uit de bijna frontale foto "Nijmegen
// NYMA-watertoren" (45 px/m, geschaald op de breedte van 12,1 m uit het AHN) en
// de telefoto vanuit de Waalsprong, gelijkgezet op de dakrand in het AHN; het
// dak uit het radiale AHN-profiel (helling 21 graden).
import { Manifold, CrossSection, ccw, hull, ring3, circle, union, box, place, writeLandmark } from "./efteling-kit.mjs";

const ORIGIN = [186049.0, 429908.65];
const AXIS = [1, 0];
const BASE = -0.3;
const GROUND_NAP = 14.29;
const SIDES = 16; // hoeken op k * 22,5 graden; de kolommen op de even hoeken
const R = {
  panel: 5.85, // hoeken van de zestienhoekige wand (panelen)
  frame: 6.1, // ringbalken
  column: 6.05, // buitenkant van de kolommen
  cornice: 6.2, // kroonlijst en dakvoet
  roofTop: 1.5, // bovenrand van het kegeldak
  skylight: 1.35,
};
const H = {
  ring3: [10.05, 10.65], // onderste ringbalk, voet van de schoren
  ring2: [15.35, 16.2],
  ring1: [21.75, 22.45], // onder de bakstenen band
  cornice: [26.1, 26.6],
  roofTop: 28.4,
  skylight: 28.55,
};
const COLUMN_WIDTH = 0.7;
const TAN55 = Math.tan((55 * Math.PI) / 180);
const deg = (d) => (d * Math.PI) / 180;
const poly = (r) => circle([0, 0], r, SIDES, 0);
const corner = (d, r = R.panel) => [r * Math.cos(deg(d)), r * Math.sin(deg(d))];

// ---------- wand, kolommen, ringbalken, kroonlijst en dak ----------
const wall = hull([...ring3(poly(R.panel), BASE), ...ring3(poly(R.panel), H.cornice[0])]);
// Kolom op een hoek, van de onderkant tot in de kroonlijst.
const column = box(R.panel - 0.4, -COLUMN_WIDTH / 2, BASE, R.column, COLUMN_WIDTH / 2, H.cornice[0] + 0.05);
const columns = union(Array.from({ length: 8 }, (_, k) => place(column, { deg: k * 45 })));
// Ringbalk met een onderkant onder 55 graden naar de wand.
const ring = ([z0, z1], r) =>
  hull([...ring3(poly(R.panel - 0.05), z0), ...ring3(poly(r), z0 + (r - R.panel + 0.05) * TAN55), ...ring3(poly(r), z1), ...ring3(poly(R.panel - 0.05), z1)]);
const rings = union([ring(H.ring3, R.frame), ring(H.ring2, R.frame), ring(H.ring1, R.frame)]);
// Kroonlijst en laag kegeldak in één omhulsel: onderkant onder 55 graden, dakvlakken tot de bovenrand.
const corniceZ = H.cornice[0] - (R.cornice - R.panel + 0.05) * TAN55;
const roof = hull([
  ...ring3(poly(R.panel - 0.05), corniceZ), ...ring3(poly(R.cornice), H.cornice[0]), ...ring3(poly(R.cornice), H.cornice[1]),
  ...ring3(poly(R.roofTop), H.roofTop),
]);
const skylight = hull([...ring3(poly(R.skylight), H.roofTop - 0.2), ...ring3(poly(R.skylight), H.skylight)]);

// ---------- schoren onder de tweede ringbalk ----------
// Zigzag: van elke tweede kolom onder de ringbalk naar de buurkolommen op de
// onderste ringbalk, over de oneven hoek ertussen (helling circa 46 graden).
// Als band op de wand, 0,7 m breed en 0,2 m dik, met de flanken onder
// 37 graden afgeschuind, zodat de onderflank steiler staat dan 45 graden.
const sub = (a, b) => a.map((c, i) => c - b[i]);
const add = (a, b, s = 1) => a.map((c, i) => c + b[i] * s);
const unit = (v) => v.map((c) => c / Math.hypot(...v));
const cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
const band = (aDeg, za, bDeg, zb, w0 = 0.7, w1 = 0.4, t = 0.2) => {
  const A = [...corner(aDeg), za];
  const B = [...corner(bDeg), zb];
  const m = deg((aDeg + bDeg) / 2);
  const n = [Math.cos(m), Math.sin(m), 0];
  const d = unit(sub(B, A));
  const w = unit(cross(n, d));
  const pts = [];
  for (const [P, s] of [[A, -0.25], [B, 0.25]]) {
    const c = add(P, d, s);
    for (const sg of [-1, 1]) {
      pts.push(add(add(c, w, (sg * w0) / 2), n, -0.1), add(c, w, (sg * w0) / 2), add(add(c, w, (sg * w1) / 2), n, t));
    }
  }
  return hull(pts);
};
const zTop = H.ring2[0];
const zBottom = H.ring3[1];
const zMid = (zTop + zBottom) / 2;
const braces = union(
  [0, 90, 180, 270].flatMap((a) =>
    [-1, 1].flatMap((s) => [band(a, zTop, a + s * 22.5, zMid), band(a + s * 22.5, zMid, a + s * 45, zBottom)]),
  ),
);

const tower = union([wall, columns, rings, roof, skylight, braces]);

// ---------- fabriek: de rest van BAG-pand 0268100000015629 ----------
// Elk dakvlak van de 3D BAG als prisma vanaf de onderkant, afgesneden door het
// vlak z = a x + b y + c (kleinste kwadraten door de hoekpunten). De
// torendelen (hoger dan NAP +30 m) liggen als vlak op 5,1 m, de hoogte van het
// fabrieksdak rond de toren, zodat er geen spleet blijft tussen de toren en
// het dak waar de 3D BAG-toren breder is.
const TOWER_FILL = 5.1;
const xyz = (flat) => Array.from({ length: flat.length / 3 }, (_, i) => flat.slice(i * 3, i * 3 + 3));
const fitPlane = (pts) => {
  // Normaalvergelijkingen voor z = a x + b y + c rond het zwaartepunt.
  const n = pts.length;
  const [mx, my, mz] = [0, 1, 2].map((k) => pts.reduce((s, p) => s + p[k], 0) / n);
  let sxx = 0, sxy = 0, syy = 0, sxz = 0, syz = 0;
  for (const [x, y, z] of pts) {
    const [u, v, w] = [x - mx, y - my, z - mz];
    sxx += u * u; sxy += u * v; syy += v * v; sxz += u * w; syz += v * w;
  }
  const det = sxx * syy - sxy * sxy;
  const a = Math.abs(det) < 1e-9 ? 0 : (sxz * syy - syz * sxy) / det;
  const b = Math.abs(det) < 1e-9 ? 0 : (syz * sxx - sxz * sxy) / det;
  return [a, b, mz - a * mx - b * my];
};
const roofPrism = ([isTower, outer, ...holes]) => {
  const pts = xyz(outer);
  const [a, b, c] = isTower ? [0, 0, TOWER_FILL] : fitPlane(pts);
  const outline = ccw(pts.map(([x, y]) => [x, y]));
  const inner = holes.map((h) => [...ccw(xyz(h).map(([x, y]) => [x, y]))].reverse());
  const top = Math.max(...pts.map(([x, y]) => a * x + b * y + c)) + 1;
  const len = Math.hypot(a, b, 1);
  // 2 cm verbreed, zodat aangrenzende vlakken en de vier dakopbouwen (eigen
  // 3D BAG-delen in gaten van het hoofddak) overlappen en één solid vormen.
  return Manifold.extrude(new CrossSection([outline, ...inner]).offset(0.02, "Miter"), top - BASE)
    .translate([0, 0, BASE])
    .trimByPlane([a / len, b / len, -1 / len], -c / len);
};
const factory = union(fabriekBag3d().faces.map(roofPrism));

